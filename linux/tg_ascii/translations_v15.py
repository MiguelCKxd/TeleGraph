assert all(len(row) == len(KEYS) for row in ROWS.values()), {code: len(row) for code, row in ROWS.items()}


def values(code):
    return dict(zip(KEYS, ROWS[code]))


def pack_values():
    """Labels stored in the on-demand JSON packs (tools/merge_locale_pack.py)."""
    from .translations_extended import NEW_LANGUAGES
    packs = {}
    for code in NEW_LANGUAGES:
        if code in ROWS:
            packs[code] = values(code)
    return packs


def extend(catalogues):
    from .translations_extended import NEW_LANGUAGES
    for code in ROWS:
        if code in NEW_LANGUAGES or code in PACK_LANGUAGES:
            continue  # Their JSON pack carries these labels.
        target = catalogues.setdefault(code, {})
        if isinstance(target, dict):
            target.update(values(code))
